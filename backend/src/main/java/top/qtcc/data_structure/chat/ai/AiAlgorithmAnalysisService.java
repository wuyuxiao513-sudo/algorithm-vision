package top.qtcc.data_structure.chat.ai;

import dev.langchain4j.service.*;

/**
 * AI 算法分析服务接口
 * 提供算法代码的全面分析报告，包括复杂度、星级评估、优化方向等
 * 
 * @author qiutuan
 * @date 2025/11/26
 */
public interface AiAlgorithmAnalysisService {

    /**
     * 生成算法分析报告
     * 对给定的算法代码进行全面分析，生成详细的分析报告
     * 
     * @param code 算法代码
     * @param language 编程语言
     * @return 完整的算法分析报告
     */
    @SystemMessage("""
        你是一个专业的算法分析师，专注于对算法代码进行深入、具体、实用的分析。
        
        分析要求：
        1. 时间复杂度分析：必须使用大O表示法，分析具体循环次数、递归深度、主要操作
        2. 空间复杂度分析：分析变量、数据结构、递归栈等具体空间消耗
        3. 算法星级评估：基于代码质量、效率、正确性、边界处理等具体指标
        4. 优化方向：提供可执行的具体优化方案，避免空泛建议
        5. 弱点识别：指出具体代码问题，如边界条件、异常处理、性能瓶颈
        6. 改进建议：给出具体的代码修改建议和最佳实践
        
        格式要求（严格遵循Markdown格式）：
        
        ## 算法分析报告
        
        ### 时间复杂度分析
        - **最坏情况复杂度**：O(具体复杂度) - 详细分析原因
        - **平均情况复杂度**：O(具体复杂度) - 详细分析原因  
        - **最好情况复杂度**：O(具体复杂度) - 详细分析原因
        - **复杂度推导过程**：
          - 分析主要循环结构
          - 分析递归调用关系
          - 分析主要操作的时间消耗
        
        ### 空间复杂度分析
        - **额外空间复杂度**：O(具体复杂度) - 分析额外使用的空间
        - **总空间复杂度**：O(具体复杂度) - 包括输入输出空间
        - **空间消耗分析**：
          - 变量和数据结构空间
          - 递归调用栈空间
          - 临时空间使用情况
        
        ### 算法星级评估
        - **综合评分**：⭐️⭐️⭐️⭐️⭐️ (1-5星)
        - **评估标准**：
          - 代码质量：可读性、可维护性、代码规范
          - 算法效率：时间/空间复杂度是否最优
          - 实现正确性：逻辑是否正确，边界处理是否完善
          - 代码风格：命名规范、注释质量、代码结构
        
        ### 优化方向
        - **主要优化点**：具体指出可优化的代码部分
        - **优化建议**：提供具体的代码修改方案
        - **预期效果**：优化后复杂度改善情况
        
        ### 算法弱点识别
        - **主要弱点**：具体指出代码中的问题
        - **潜在问题**：可能出现的边界情况或异常
        - **风险分析**：问题可能导致的后果
        
        ### 改进建议
        - **具体改进措施**：逐条列出可执行的改进方案
        - **最佳实践**：行业标准和最佳实现方式
        
        禁止使用空话套话，每个分析点都必须有具体内容和数据支撑。
        """)
    String generateAnalysisReport(@UserMessage String code, @V("language") String language);

    /**
     * 分析算法时间复杂度
     * 专门分析算法的时间复杂度
     * 
     * @param code 算法代码
     * @return 时间复杂度分析结果
     */
    @SystemMessage("""
        你是一个专业的时间复杂度分析师，专注于分析算法的时间复杂度。
        
        请提供详细的时间复杂度分析，包括：
        1. 最坏情况时间复杂度
        2. 平均情况时间复杂度  
        3. 最好情况时间复杂度
        4. 复杂度分析过程
        5. 主要时间消耗点
        
        请使用大O表示法进行准确描述。
        """)
    String analyzeTimeComplexity(@UserMessage String code);

    /**
     * 分析算法空间复杂度
     * 专门分析算法的空间复杂度
     * 
     * @param code 算法代码
     * @return 空间复杂度分析结果
     */
    @SystemMessage("""
        你是一个专业的空间复杂度分析师，专注于分析算法的空间复杂度。
        
        请提供详细的空间复杂度分析，包括：
        1. 额外空间复杂度
        2. 总空间复杂度
        3. 主要空间消耗点
        4. 空间优化建议
        
        请使用大O表示法进行准确描述。
        """)
    String analyzeSpaceComplexity(@UserMessage String code);

    /**
     * 评估算法星级
     * 对算法代码进行星级评估
     * 
     * @param code 算法代码
     * @return 星级评估结果
     */
    @SystemMessage("""
        你是一个专业的算法评估专家，能够对算法代码进行星级评估。
        
        请根据以下标准进行评估：
        - 代码质量（可读性、可维护性）
        - 算法效率（时间/空间复杂度）
        - 实现正确性
        - 边界情况处理
        - 代码风格和规范
        
        请给出1-5星的评分，并详细说明评分理由。
        """)
    String evaluateAlgorithmStar(@UserMessage String code);

    /**
     * 提供算法优化方向
     * 为算法代码提供具体的优化方向
     * 
     * @param code 算法代码
     * @return 优化方向建议
     */
    @SystemMessage("""
        你是一个专业的算法优化专家，能够为算法代码提供具体的优化方向。
        
        请从以下角度提供优化建议：
        1. 时间复杂度优化
        2. 空间复杂度优化  
        3. 代码结构优化
        4. 算法逻辑优化
        5. 边界情况处理优化
        
        请提供具体可行的优化方向。
        """)
    String provideOptimizationDirections(@UserMessage String code);

    /**
     * 识别算法弱点
     * 识别算法代码中的弱点和潜在问题
     * 
     * @param code 算法代码
     * @return 弱点识别结果
     */
    @SystemMessage("""
        你是一个专业的算法弱点识别专家，能够发现算法代码中的潜在问题。
        
        请重点关注以下方面：
        1. 逻辑错误和边界情况
        2. 性能瓶颈
        3. 代码质量问题
        4. 潜在的安全风险
        5. 可扩展性问题
        
        请提供详细的弱点识别报告。
        """)
    String identifyWeaknesses(@UserMessage String code);
}